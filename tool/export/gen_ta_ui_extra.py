import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from ta_ui_map import M
from ta_ui_map2 import M2
from ta_ui_map3 import M3
M = {**M, **M2, **M3}

def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"

out = ['// GENERATED by tool/export/gen_ta_ui_extra.py - do not edit by hand.',
       '// Tamil wording of fixed UI strings (see TaUi).',
       'const taUiExtra = <String, String>{']
for k, v in M.items():
    out.append('  %s: %s,' % (q(k), q(v)))
out.append('};')
root = os.path.join(os.path.dirname(__file__), '..', '..', 'lib', 'l10n', 'ta_ui_extra.dart')
with open(root, 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print(len(M), 'entries')
