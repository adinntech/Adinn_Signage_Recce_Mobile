# Generates lib/l10n/ta_catalog.dart from the Tamil wording of the vendor
# workbook (the dictionaries in build_vendor_excel.py). Display only.
import re, os
src = open('tool/export/build_vendor_excel.py', encoding='utf8').read()
head = src.split('# ----------------------------------------------------------------- source lines')[0]
ns = {}
exec(head, ns)

def esc(s): return s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
def emit(name, d):
    lines = [f"  static const {name} = <String, String>{{"]
    for k, v in d.items():
        lines.append(f"    '{esc(k)}': '{esc(v)}',")
    lines.append('  };')
    return '\n'.join(lines)

media = {  # display names (stored codes never change)
 'GSB Single Side': ns['MEDIA_TA']['GSB_SINGLE'], 'GSB Double Side': ns['MEDIA_TA']['GSB_DOUBLE'],
 'NLB Single Side': ns['MEDIA_TA']['NLB_SINGLE_FRAME'], 'NLB Double Side': ns['MEDIA_TA']['NLB_BOX_FRAME'],
 'Foam Vinyl': ns['MEDIA_TA']['FOAM_VINYL'], 'Acrylic': ns['MEDIA_TA']['ACRYLIC'],
 'One-Way Vision': ns['MEDIA_TA']['OWV'], 'Plain Vinyl': ns['MEDIA_TA']['PLAIN_VINYL'], 'MDF': ns['MEDIA_TA']['MDF'],
}
out = ["// GENERATED by tool/export/gen_ta_catalog.py - Tamil display wording from the vendor workbook.",
       "// Display only: ids, codes, answer values and user content are never translated.",
       "class TaCatalog {", "  TaCatalog._();", "",
       emit('questions', ns['Q_TA']), "", emit('options', ns['OPT_TA']), "",
       emit('installations', {k: v for k, v in ns['INST_TA'].items()}), "", emit('media', media), "}"]
open('lib/l10n/ta_catalog.dart', 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(len(ns['Q_TA']), len(ns['OPT_TA']), len(ns['INST_TA']))
